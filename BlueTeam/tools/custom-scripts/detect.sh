    echo -e "${NC}"
}

# Logging functions
log() { echo -e "${GREEN}[+]${NC} $1" | tee -a "$LOG_FILE"; }
warn() { echo -e "${YELLOW}[!]${NC} $1" | tee -a "$LOG_FILE"; }
error() { echo -e "${RED}[✗]${NC} $1" | tee -a "$LOG_FILE"; }
alert() { echo -e "${RED}[🚨]${NC} $1" | tee -a "$LOG_FILE"; }
info() { echo -e "${BLUE}[i]${NC} $1" | tee -a "$LOG_FILE"; }

# Create alert file
create_alert() {
    local severity=$1
    local title=$2
    local description=$3
    local iocs=$4
    local mitre=$5
    
    local alert_file="$ALERTS_DIR/$severity/alert_$(date +%Y%m%d_%H%M%S)_$RANDOM.md"
    mkdir -p "$ALERTS_DIR/$severity"
    
    cat > "$alert_file" << EOF
# 🚨 Security Alert - ${severity^^}

**Date:** $(date '+%Y-%m-%d %H:%M:%S')
**Host:** $(hostname)
**User:** $(whoami)

## Description
$title

$description

## Indicators of Compromise (IOCs)
$iocs

## MITRE ATT&CK Mapping
$mitre

## Recommended Actions
- Investigate the affected system
- Check for lateral movement
- Review related logs
- Consider containment if necessary

---
*Generated by BlueTeam-Windsurf Detection System*
EOF
    
    echo "$alert_file"
}

