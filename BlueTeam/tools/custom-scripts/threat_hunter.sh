    fi
    
    # T1021.002 - SMB/Windows Admin Shares
    info "Checking SMB connections (T1021.002)..."
    local smb_conns
    smb_conns=$(ss -tunapl 2>/dev/null | grep -E ":(445|139)" || true)
    if [ -n "$smb_conns" ]; then
        warn "SMB connections detected:"
        echo "$smb_conns" | tee -a "$HUNT_LOG"
    fi
    
    # T1021.004 - SSH
    info "Checking for SSH key usage..."
    
    # SSH agent
    if [ -n "$SSH_AUTH_SOCK" ]; then
        local ssh_keys
        ssh_keys=$(ssh-add -l 2>/dev/null || true)
        if [ -n "$ssh_keys" ]; then
            info "SSH keys in agent:"
            echo "$ssh_keys" | tee -a "$HUNT_LOG"
        fi
    fi
    
    # T1570 - Lateral Tool Transfer
    info "Checking for tool transfer indicators (T1570)..."
    
    # Recent file transfers
    local transfers
    transfers=$(grep -E "(scp|rsync|wget|curl)" /var/log/auth.log /var/log/syslog 2>/dev/null | tail -20 || true)
    if [ -n "$transfers" ]; then
        info "Recent file transfer activity:"
        echo "$transfers" | tee -a "$HUNT_LOG"
    fi
    
    # Files in /tmp from other hosts
    local tmp_files
    tmp_files=$(find /tmp /var/tmp -type f -mtime -1 -size +1M 2>/dev/null | head -10 || true)
