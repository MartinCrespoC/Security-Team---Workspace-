#===============================================================================
# MAIN
#===============================================================================

main() {
    show_banner
    
    mkdir -p "$(dirname "$HUNT_LOG")"
    mkdir -p "$FINDINGS_DIR"
    
    if [ $# -eq 0 ]; then
        full_hunt
        exit 0
    fi
    
    while [ $# -gt 0 ]; do
        case "$1" in
            --hunt-all)
                full_hunt
                ;;
            --persistence)
                hunt_persistence
                ;;
            --privesc)
                hunt_privilege_escalation
                ;;
            --evasion)
                hunt_defense_evasion
                ;;
            --lateral)
                hunt_lateral_movement
                ;;
            --c2)
                hunt_c2
                ;;
            --exfil)
                hunt_exfiltration
                ;;
            --creds)
                hunt_credential_access
                ;;
            -h|--help)
                usage
                exit 0
                ;;
            *)
                error "Unknown option: $1"
                usage
                exit 1
                ;;
        esac
        shift
    done
    
    log "Hunt completed. Results: $HUNT_LOG"
}

main "$@"
