# PERSISTENCE HUNTING (TA0003)
#===============================================================================

hunt_persistence() {
    log "🔍 Hunting for Persistence Mechanisms (TA0003)..."
    echo ""
    
    local found=0
    
    # T1053 - Scheduled Tasks/Cron
    info "Checking scheduled tasks (T1053)..."
    
    # User crontabs
    for crontab in /var/spool/cron/crontabs/*; do
        if [ -f "$crontab" ]; then
            local suspicious
            suspicious=$(grep -E "(curl|wget|nc|bash|python|perl|php|ruby|\.sh)" "$crontab" 2>/dev/null || true)
            if [ -n "$suspicious" ]; then
                alert "Suspicious crontab entry found in $crontab"
                echo "$suspicious" | tee -a "$HUNT_LOG"
                create_finding "T1053" "Suspicious Crontab" "Found suspicious entry in $crontab" "$suspicious"
                found=1
            fi
        fi
    done
    
    # System crontabs
    for crondir in /etc/cron.d /etc/cron.daily /etc/cron.hourly /etc/cron.weekly /etc/cron.monthly; do
        if [ -d "$crondir" ]; then
            local suspicious
            suspicious=$(grep -rE "(curl|wget|nc|bash -c|python -c|perl -e)" "$crondir" 2>/dev/null || true)
            if [ -n "$suspicious" ]; then
                alert "Suspicious cron entry in $crondir"
                echo "$suspicious" | tee -a "$HUNT_LOG"
                found=1
            fi
        fi
    done
    
    # T1543 - Systemd Services
    info "Checking systemd services (T1543)..."
    
    # Recently created services
    local recent_services
    recent_services=$(find /etc/systemd/system /usr/lib/systemd/system -name "*.service" -mtime -7 2>/dev/null || true)
    if [ -n "$recent_services" ]; then
        warn "Recently created/modified systemd services:"
        echo "$recent_services" | tee -a "$HUNT_LOG"
        
        for svc in $recent_services; do
            if grep -qE "(curl|wget|nc|bash|python|perl|/tmp/|/dev/shm/)" "$svc" 2>/dev/null; then
                alert "Suspicious service: $svc"
                cat "$svc" >> "$HUNT_LOG"
                found=1
            fi
        done
    fi
    
    # T1547 - Boot/Logon Autostart
    info "Checking autostart locations (T1547)..."
    
    # rc.local
    if [ -f /etc/rc.local ]; then
        local rclocal
        rclocal=$(grep -vE "^#|^$|^exit" /etc/rc.local 2>/dev/null || true)
        if [ -n "$rclocal" ]; then
            warn "Commands in /etc/rc.local:"
            echo "$rclocal" | tee -a "$HUNT_LOG"
        fi
    fi
    
    # init.d scripts
    local recent_init
    recent_init=$(find /etc/init.d -type f -mtime -7 2>/dev/null || true)
    if [ -n "$recent_init" ]; then
        warn "Recently modified init.d scripts:"
        echo "$recent_init" | tee -a "$HUNT_LOG"
    fi
    
    # T1546 - Event Triggered Execution
    info "Checking event triggers (T1546)..."
    
    # .bashrc/.profile modifications
    for profile in /home/*/.bashrc /home/*/.bash_profile /home/*/.profile /root/.bashrc /root/.profile; do
        if [ -f "$profile" ]; then
            local suspicious
            suspicious=$(grep -E "(curl|wget|nc|python|perl|base64|eval)" "$profile" 2>/dev/null || true)
            if [ -n "$suspicious" ]; then
                alert "Suspicious entry in $profile"
                echo "$suspicious" | tee -a "$HUNT_LOG"
                found=1
            fi
        fi
    done
    
    # T1098 - Account Manipulation
    info "Checking for account manipulation (T1098)..."
    
    # Users with UID 0
    local uid0
    uid0=$(awk -F: '($3 == 0) {print $1}' /etc/passwd | grep -v "^root$" || true)
    if [ -n "$uid0" ]; then
        alert "Non-root users with UID 0:"
        echo "$uid0" | tee -a "$HUNT_LOG"
        found=1
    fi
    
    # Users with no password
    local nopass
    nopass=$(awk -F: '($2 == "" || $2 == "!") {print $1}' /etc/shadow 2>/dev/null || true)
    if [ -n "$nopass" ]; then
        warn "Users with no/disabled password:"
        echo "$nopass" | tee -a "$HUNT_LOG"
    fi
    
    # Recently added users
    local recent_users
    recent_users=$(grep -E "useradd|adduser" /var/log/auth.log 2>/dev/null | tail -10 || true)
    if [ -n "$recent_users" ]; then
        info "Recent user additions:"
        echo "$recent_users" | tee -a "$HUNT_LOG"
    fi
    
    # SSH authorized_keys
    info "Checking SSH keys (T1098.004)..."
    for authkeys in /home/*/.ssh/authorized_keys /root/.ssh/authorized_keys; do
        if [ -f "$authkeys" ]; then
            local keycount
            keycount=$(wc -l < "$authkeys")
            if [ "$keycount" -gt 0 ]; then
                info "Found $keycount SSH keys in $authkeys"
                # Check for recently added keys
                if [ "$(find "$authkeys" -mtime -7 2>/dev/null)" ]; then
                    warn "SSH keys file recently modified: $authkeys"
                fi
            fi
        fi
    done
    
    if [ $found -eq 0 ]; then
        log "No persistence mechanisms found"
    fi
    
    echo ""
}

