# COMMAND AND CONTROL HUNTING (TA0011)
#===============================================================================

hunt_c2() {
    log "🔍 Hunting for Command & Control (TA0011)..."
    echo ""
    
    local found=0
    
    # T1071 - Application Layer Protocol
    info "Checking for C2 traffic patterns (T1071)..."
    
    # Unusual outbound connections
    local outbound
    outbound=$(ss -tunapl 2>/dev/null | grep ESTABLISHED | grep -v "127.0.0.1" || true)
    if [ -n "$outbound" ]; then
        info "Outbound connections:"
        echo "$outbound" | tee -a "$HUNT_LOG"
    fi
    
    # Connections to unusual ports
    local unusual_ports
    unusual_ports=$(ss -tunapl 2>/dev/null | grep ESTABLISHED | grep -E ":(4444|5555|6666|1337|31337|8080|8443|9001)" || true)
    if [ -n "$unusual_ports" ]; then
        alert "Connections to suspicious ports:"
        echo "$unusual_ports" | tee -a "$HUNT_LOG"
        found=1
    fi
    
    # T1572 - Protocol Tunneling
    info "Checking for tunneling (T1572)..."
    
    # DNS tunneling indicators
    local dns_queries
    dns_queries=$(ss -tunapl 2>/dev/null | grep ":53" | wc -l || echo 0)
    if [ "$dns_queries" -gt 50 ]; then
        warn "High DNS activity ($dns_queries connections) - possible DNS tunneling"
        found=1
    fi
    
    # ICMP tunneling
    if ping -c 1 127.0.0.1 &>/dev/null; then
        local icmp_procs
        icmp_procs=$(ps aux | grep -E "(ptunnel|icmpsh|icmptunnel)" | grep -v grep || true)
        if [ -n "$icmp_procs" ]; then
            alert "ICMP tunneling tools detected:"
            echo "$icmp_procs" | tee -a "$HUNT_LOG"
            found=1
        fi
    fi
    
    # T1573 - Encrypted Channel
    info "Checking for encrypted channels (T1573)..."
    
    # SSL/TLS connections to unusual destinations
    local ssl_conns
    ssl_conns=$(ss -tunapl 2>/dev/null | grep ":443" | grep ESTABLISHED || true)
    if [ -n "$ssl_conns" ]; then
        info "HTTPS connections:"
        echo "$ssl_conns" | head -10 | tee -a "$HUNT_LOG"
    fi
    
    # T1095 - Non-Application Layer Protocol
    info "Checking for raw socket usage (T1095)..."
    
    local raw_sockets
    raw_sockets=$(ss -w 2>/dev/null || true)
    if [ -n "$raw_sockets" ]; then
        warn "Raw sockets detected:"
        echo "$raw_sockets" | tee -a "$HUNT_LOG"
    fi
    
    # Beaconing detection (regular interval connections)
    info "Checking for beaconing patterns..."
    
    # This is a simplified check - real beaconing detection needs more data
    local repeated_conns
    repeated_conns=$(ss -tunapl 2>/dev/null | awk '{print $5}' | sort | uniq -c | sort -rn | head -5 || true)
    if [ -n "$repeated_conns" ]; then
        info "Most frequent connection destinations:"
        echo "$repeated_conns" | tee -a "$HUNT_LOG"
    fi
    
    if [ $found -eq 0 ]; then
        log "No C2 indicators found"
    fi
    
    echo ""
}

