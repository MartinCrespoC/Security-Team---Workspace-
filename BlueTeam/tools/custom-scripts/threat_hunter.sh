hunt_exfiltration() {
    log "🔍 Hunting for Data Exfiltration (TA0010)..."
    echo ""
    
    local found=0
    
    # T1048 - Exfiltration Over Alternative Protocol
    info "Checking for exfiltration indicators (T1048)..."
    
    # Large outbound transfers
    local large_transfers
    large_transfers=$(find /tmp /var/tmp /home -name "*.tar*" -o -name "*.zip" -o -name "*.7z" -mtime -1 2>/dev/null | head -10 || true)
    if [ -n "$large_transfers" ]; then
        warn "Recent archive files (possible staging):"
        echo "$large_transfers" | tee -a "$HUNT_LOG"
        for f in $large_transfers; do
            ls -lh "$f" >> "$HUNT_LOG" 2>/dev/null || true
        done
    fi
    
    # T1041 - Exfiltration Over C2 Channel
    info "Checking for data staging (T1041)..."
    
    # Files with sensitive data patterns
    local sensitive
    sensitive=$(find /tmp /var/tmp /dev/shm -type f -exec grep -l -E "(password|secret|key|token|credential)" {} \; 2>/dev/null | head -10 || true)
    if [ -n "$sensitive" ]; then
        alert "Files with sensitive keywords in temp directories:"
        echo "$sensitive" | tee -a "$HUNT_LOG"
        found=1
    fi
    
    # T1567 - Exfiltration Over Web Service
    info "Checking for cloud upload indicators (T1567)..."
    
    # Check for cloud CLI tools
    for tool in aws gcloud az rclone; do
        if command -v "$tool" &>/dev/null; then
            info "Cloud tool installed: $tool"
            # Check recent usage
            if [ -f ~/.${tool}/credentials ] || [ -f ~/.config/${tool}/credentials ]; then
                warn "Cloud credentials found for $tool"
            fi
        fi
    done
    
    # Check for curl/wget to cloud services
    local cloud_uploads
    cloud_uploads=$(grep -rE "(s3\.amazonaws|storage\.googleapis|blob\.core\.windows)" /var/log/*.log 2>/dev/null | tail -10 || true)
    if [ -n "$cloud_uploads" ]; then
        warn "Cloud service access in logs:"
        echo "$cloud_uploads" | tee -a "$HUNT_LOG"
    fi
    
    if [ $found -eq 0 ]; then
        log "No exfiltration indicators found"
    fi
    
    echo ""
}

