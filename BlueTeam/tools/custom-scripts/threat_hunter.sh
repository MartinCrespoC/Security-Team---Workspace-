set -e

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
NC='\033[0m'

# Variables
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BASE_DIR="$(dirname "$(dirname "$SCRIPT_DIR")")"
HUNT_LOG="$BASE_DIR/logs/threat_hunt_$(date +%Y%m%d_%H%M%S).log"
FINDINGS_DIR="$BASE_DIR/alerts/hunt"

# Banner
show_banner() {
    echo -e "${CYAN}"
    echo "╔══════════════════════════════════════════════════════════════╗"
    echo "║     🎯 BlueTeam Threat Hunter                                ║"
    echo "║        MITRE ATT&CK Based Hunting                            ║"
    echo "╚══════════════════════════════════════════════════════════════╝"
    echo -e "${NC}"
}

# Logging
log() { echo -e "${GREEN}[+]${NC} $1" | tee -a "$HUNT_LOG"; }
warn() { echo -e "${YELLOW}[!]${NC} $1" | tee -a "$HUNT_LOG"; }
error() { echo -e "${RED}[✗]${NC} $1" | tee -a "$HUNT_LOG"; }
alert() { echo -e "${RED}[🎯]${NC} $1" | tee -a "$HUNT_LOG"; }
info() { echo -e "${BLUE}[i]${NC} $1" | tee -a "$HUNT_LOG"; }

# Create finding
create_finding() {
    local technique=$1
    local title=$2
    local description=$3
    local evidence=$4
    
    mkdir -p "$FINDINGS_DIR"
    local finding_file="$FINDINGS_DIR/hunt_$(date +%Y%m%d_%H%M%S)_$RANDOM.md"
    
    cat > "$finding_file" << EOF
# 🎯 Threat Hunt Finding

**Date:** $(date '+%Y-%m-%d %H:%M:%S')
**Technique:** $technique
**Title:** $title

## Description
$description

## Evidence
\`\`\`
$evidence
\`\`\`

## Recommendations
- Investigate the finding
- Correlate with other events
- Consider containment if malicious

---
*Generated by BlueTeam Threat Hunter*
EOF
    
    echo "$finding_file"
}

