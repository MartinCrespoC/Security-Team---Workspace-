        echo "$tmp_files" | tee -a "$HUNT_LOG"
        for f in $tmp_files; do
            file "$f" >> "$HUNT_LOG" 2>/dev/null || true
        done
    fi
    
    if [ $found -eq 0 ]; then
        log "No lateral movement indicators found"
    fi
    
    echo ""
}

