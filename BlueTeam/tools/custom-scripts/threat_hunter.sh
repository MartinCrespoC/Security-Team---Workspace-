# DEFENSE EVASION HUNTING (TA0005)
#===============================================================================

hunt_defense_evasion() {
    log "🔍 Hunting for Defense Evasion (TA0005)..."
    echo ""
    
    local found=0
    
    # T1070 - Indicator Removal
    info "Checking for log tampering (T1070)..."
    
    # Empty or truncated logs
    for logfile in /var/log/auth.log /var/log/syslog /var/log/messages /var/log/secure; do
        if [ -f "$logfile" ]; then
            local size
            size=$(stat -c %s "$logfile" 2>/dev/null || echo 0)
            if [ "$size" -lt 100 ]; then
                alert "Suspiciously small log file: $logfile ($size bytes)"
                found=1
            fi
        fi
    done
    
    # Check for history file tampering
    for histfile in /home/*/.bash_history /root/.bash_history; do
        if [ -f "$histfile" ]; then
            # Check if linked to /dev/null
            if [ -L "$histfile" ]; then
                local target
                target=$(readlink "$histfile")
                if [ "$target" = "/dev/null" ]; then
                    alert "History file linked to /dev/null: $histfile"
                    found=1
                fi
            fi
            # Check if empty but should have content
            if [ ! -s "$histfile" ]; then
                warn "Empty history file: $histfile"
            fi
        fi
    done
    
    # T1027 - Obfuscated Files
    info "Checking for obfuscated files (T1027)..."
    
    # Base64 encoded scripts
    local b64_scripts
    b64_scripts=$(find /tmp /var/tmp /dev/shm -type f -exec grep -l "base64" {} \; 2>/dev/null | head -10 || true)
    if [ -n "$b64_scripts" ]; then
        warn "Files with base64 content:"
        echo "$b64_scripts" | tee -a "$HUNT_LOG"
    fi
    
    # T1564 - Hidden Artifacts
    info "Checking for hidden files (T1564)..."
    
    # Hidden files in suspicious locations
    local hidden
    hidden=$(find /tmp /var/tmp /dev/shm -name ".*" -type f 2>/dev/null | head -20 || true)
    if [ -n "$hidden" ]; then
        warn "Hidden files in temp directories:"
        echo "$hidden" | tee -a "$HUNT_LOG"
        found=1
    fi
    
    # Hidden directories
    local hidden_dirs
    hidden_dirs=$(find / -maxdepth 3 -name ".. " -o -name "..." -o -name ".  " 2>/dev/null || true)
    if [ -n "$hidden_dirs" ]; then
        alert "Suspicious hidden directories:"
        echo "$hidden_dirs" | tee -a "$HUNT_LOG"
        found=1
    fi
    
    # T1014 - Rootkit Detection
    info "Checking for rootkit indicators (T1014)..."
    
    # Compare ps and /proc
    local ps_count
    local proc_count
    ps_count=$(ps aux | wc -l)
    proc_count=$(ls -d /proc/[0-9]* 2>/dev/null | wc -l)
    
    if [ $((proc_count - ps_count)) -gt 10 ]; then
        alert "Process count discrepancy (possible hidden processes)"
        alert "ps shows $ps_count, /proc shows $proc_count"
        found=1
    fi
    
    # Check for suspicious kernel modules
    local suspicious_mods
    suspicious_mods=$(lsmod | awk '{print $1}' | while read -r mod; do
        if ! modinfo "$mod" &>/dev/null; then
            echo "$mod"
        fi
    done || true)
    
    if [ -n "$suspicious_mods" ]; then
        alert "Kernel modules without modinfo:"
        echo "$suspicious_mods" | tee -a "$HUNT_LOG"
        found=1
    fi
    
    # T1562 - Impair Defenses
    info "Checking security tool status (T1562)..."
    
    # Check if security tools are disabled
    for service in auditd fail2ban ufw iptables apparmor selinux; do
        if command -v systemctl &>/dev/null; then
            if systemctl is-enabled "$service" &>/dev/null; then
                if ! systemctl is-active "$service" &>/dev/null; then
                    warn "Security service not running: $service"
                fi
            fi
        fi
    done
    
    # Check iptables rules
    local iptables_rules
    iptables_rules=$(iptables -L -n 2>/dev/null | grep -c "^" || echo 0)
    if [ "$iptables_rules" -lt 5 ]; then
        warn "Very few iptables rules ($iptables_rules) - firewall may be disabled"
    fi
    
    if [ $found -eq 0 ]; then
        log "No defense evasion indicators found"
    fi
    
    echo ""
}

