# PRIVILEGE ESCALATION HUNTING (TA0004)
#===============================================================================

hunt_privilege_escalation() {
    log "🔍 Hunting for Privilege Escalation (TA0004)..."
    echo ""
    
    local found=0
    
    # T1548 - SUID/SGID Abuse
    info "Checking SUID binaries (T1548)..."
    
    local known_suid="/usr/bin/sudo /usr/bin/su /usr/bin/passwd /usr/bin/chsh /usr/bin/chfn /usr/bin/newgrp /usr/bin/gpasswd /usr/bin/mount /usr/bin/umount /usr/bin/pkexec /usr/bin/crontab /usr/bin/at /usr/bin/ssh-agent /usr/lib/openssh/ssh-keysign /usr/lib/dbus-1.0/dbus-daemon-launch-helper /usr/lib/policykit-1/polkit-agent-helper-1"
    
    while IFS= read -r suid; do
        if ! echo "$known_suid" | grep -q "$suid"; then
            warn "Unusual SUID binary: $suid"
            ls -la "$suid" >> "$HUNT_LOG"
            found=1
        fi
    done < <(find /usr /bin /sbin -perm -4000 -type f 2>/dev/null)
    
    # SGID binaries
    local sgid_bins
    sgid_bins=$(find /usr /bin /sbin -perm -2000 -type f 2>/dev/null | head -20 || true)
    if [ -n "$sgid_bins" ]; then
        info "SGID binaries found:"
        echo "$sgid_bins" | head -10 | tee -a "$HUNT_LOG"
    fi
    
    # T1548.003 - Sudo Abuse
    info "Checking sudo configuration (T1548.003)..."
    
    # NOPASSWD entries
    local nopasswd
    nopasswd=$(grep -r "NOPASSWD" /etc/sudoers /etc/sudoers.d/ 2>/dev/null || true)
    if [ -n "$nopasswd" ]; then
        warn "NOPASSWD sudo entries found:"
        echo "$nopasswd" | tee -a "$HUNT_LOG"
    fi
    
    # Dangerous sudo permissions
    local dangerous_sudo
    dangerous_sudo=$(grep -rE "(ALL.*ALL|NOPASSWD.*ALL|!/)" /etc/sudoers /etc/sudoers.d/ 2>/dev/null || true)
    if [ -n "$dangerous_sudo" ]; then
        warn "Potentially dangerous sudo permissions:"
        echo "$dangerous_sudo" | tee -a "$HUNT_LOG"
    fi
    
    # T1068 - Exploitation for Privilege Escalation
    info "Checking for exploitation indicators (T1068)..."
    
    # Core dumps
    local coredumps
    coredumps=$(find /var/crash /tmp /var/tmp -name "core*" -o -name "*.core" 2>/dev/null | head -10 || true)
    if [ -n "$coredumps" ]; then
        warn "Core dumps found (possible exploitation):"
        echo "$coredumps" | tee -a "$HUNT_LOG"
    fi
    
    # Capabilities
    info "Checking file capabilities..."
    local caps
    caps=$(getcap -r / 2>/dev/null | grep -v "^$" | head -20 || true)
    if [ -n "$caps" ]; then
        info "Files with capabilities:"
        echo "$caps" | tee -a "$HUNT_LOG"
        
        # Check for dangerous capabilities
        if echo "$caps" | grep -qE "(cap_setuid|cap_setgid|cap_sys_admin|cap_sys_ptrace)"; then
            warn "Dangerous capabilities found!"
            found=1
        fi
    fi
    
    # World-writable directories in PATH
    info "Checking PATH for world-writable directories..."
    IFS=':' read -ra PATHDIRS <<< "$PATH"
    for dir in "${PATHDIRS[@]}"; do
        if [ -d "$dir" ] && [ -w "$dir" ] && [ "$(stat -c %a "$dir" 2>/dev/null)" = "777" ]; then
            alert "World-writable directory in PATH: $dir"
            found=1
        fi
    done
    
    if [ $found -eq 0 ]; then
        log "No privilege escalation indicators found"
    fi
    
    echo ""
}

